/** The `odoo` command of a workspace: a launcher next to the versions and an optional PATH dispatcher. */

export const CLI_MARKER = "# Generated by the OpenCode Odoo plugin"

export interface CliState {
  /** The virtualenv python of the configuration's version. */
  python: string
  /** The `odoo-bin` of the configuration's version. */
  odooBin: string
  /** The active `odoo.conf`. */
  conf: string
}

function quote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`
}

/** The file the launcher sources: it always names the active configuration, so switching it needs no new script. */
export function cliState(state: CliState): string {
  return [
    CLI_MARKER,
    `PYTHON=${quote(state.python)}`,
    `ODOO_BIN=${quote(state.odooBin)}`,
    `CONF=${quote(state.conf)}`,
    "",
  ].join("\n")
}

/** `<workspace>/bin/odoo`: runs Odoo with the active odoo.conf unless the arguments pass their own `-c`. */
export function cliLauncher(): string {
  return `#!/usr/bin/env bash
${CLI_MARKER}: runs this workspace's Odoo with the active odoo.conf.
set -euo pipefail

SOURCE="\${BASH_SOURCE[0]}"
while [[ -L "\${SOURCE}" ]]; do
  TARGET="$(readlink "\${SOURCE}")"
  if [[ "\${TARGET}" != /* ]]; then TARGET="$(cd "$(dirname "\${SOURCE}")" && pwd)/\${TARGET}"; fi
  SOURCE="\${TARGET}"
done
ROOT="$(cd "$(dirname "\${SOURCE}")/.." && pwd)"
STATE="\${ROOT}/.odoo-run/odoo-cli.env"

PYTHON="\${ROOT}/.venv/bin/python"
ODOO_BIN="\${ROOT}/odoo/odoo-bin"
CONF="\${ROOT}/config/odoo.conf"
if [[ -f "\${STATE}" ]]; then
  # shellcheck disable=SC1090
  source "\${STATE}"
fi

prepend_path_dir() {
  local dir="$1"
  if [[ -d "\${dir}" ]]; then
    case ":\${PATH}:" in
      *":\${dir}:"*) ;;
      *) export PATH="\${dir}:\${PATH}" ;;
    esac
  fi
}
if command -v brew >/dev/null 2>&1; then
  prepend_path_dir "$(brew --prefix libpq 2>/dev/null)/bin"
fi
prepend_path_dir "/opt/homebrew/opt/libpq/bin"
prepend_path_dir "/usr/local/opt/libpq/bin"

if [[ ! -x "\${PYTHON}" ]]; then
  echo "odoo: no python at \${PYTHON}. Install this version from the Odoo panel." >&2
  exit 1
fi
if [[ ! -f "\${ODOO_BIN}" ]]; then
  echo "odoo: no odoo-bin at \${ODOO_BIN}" >&2
  exit 1
fi
if [[ ! -f "\${CONF}" ]]; then
  echo "odoo: no configuration at \${CONF}" >&2
  exit 1
fi

has_conf=0
for arg in "$@"; do
  case "\${arg}" in
    -c|--config|--config=*|-c=*) has_conf=1 ;;
  esac
done
if [[ "\${has_conf}" -eq 0 ]]; then
  exec "\${PYTHON}" "\${ODOO_BIN}" -c "\${CONF}" "$@"
fi
exec "\${PYTHON}" "\${ODOO_BIN}" "$@"
`
}

/** `~/.local/bin/odoo`: runs the nearest `bin/odoo` above the current directory, so each workspace keeps its own. */
export function cliDispatcher(): string {
  return `#!/usr/bin/env bash
${CLI_MARKER}: runs the nearest workspace bin/odoo above this directory.
set -euo pipefail

dir="\${PWD}"
while [[ -n "\${dir}" ]]; do
  if [[ -x "\${dir}/bin/odoo" ]]; then
    exec "\${dir}/bin/odoo" "$@"
  fi
  if [[ "\${dir}" == "/" ]]; then break; fi
  dir="$(dirname "\${dir}")"
done
echo "odoo: no bin/odoo found above \${PWD}" >&2
exit 1
`
}
